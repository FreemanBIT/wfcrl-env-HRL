"""
generate_turbsim_inputs.py — 生成"每间距一个盒"的 TurbSim .inp 文件。

背景（为什么需要按间距加宽盒子）
--------------------------------------------------------------------------
本工程用"风场旋转法"处理非零风向：把单列风机绕质心旋转 -offset，使入流沿 +X。
于是外侧风机的横向坐标随 offset×spacing 增大（Y-span = (n-1)*spacing*sin|offset|），
在 8D/±20° 可达 ±345 m（列展宽 5.47D）。此时 800 m 宽的通用盒**放不下**外侧
风机的转子高分辨率盒，FAST.Farm 运行期报：
    Grid4DField_GetVel: Outside the grid bounds ...
（正对风 offset=0 的工况 Y-span=0，800 盒够用，所以只有偏差工况失败。）

解决：为每个 (风速, TI, 间距) 生成一个**足够宽**的专用盒，命名带 _s{spacing}D，
create_ff_case / inflow_bts_for_case 会自动优先使用它。盒宽按该间距的最大偏差
(±20°) 计算，故同一间距的所有 offset 共用一个盒。

用法
--------------------------------------------------------------------------
    python -m induction_vs_yaw_study.turbsim_inp.generate_turbsim_inputs \
        --out ./FarmInputs

生成后，用 TurbSim 逐个跑这些 .inp 得到 .bts，放入工程的 FarmInputs 目录。
（TurbSim 需本地自备；生成 36 个盒可能耗时较长，可用附带的 run_all_turbsim.bat。）

参数依据（与前几轮一致，勿随意改动 HubHt/GridHeight）
--------------------------------------------------------------------------
  HubHt        = 175   （与工程既有可用盒一致；转子完整落在盒内）
  GridHeight   = 340
  NumGrid_Z    = 40
  AnalysisTime = 600   （单算例需 t_settle(360)+50*3=510s，留余量）
  RefHt        = 90    （NTM 参考高度）
  URef         = 风速  （6/8/10）
  IECturbc     = TI%   （5.0 / 10.0 / 15.0，对应 0.05/0.10/0.15）
  GridWidth / NumGrid_Y : 按间距自适应（见下），保证 dY_box <= 9.43（6m/s 约束）
"""
from __future__ import annotations

import argparse
import math
import os
from pathlib import Path

# ---- 扫描维度（与 grid 主配置保持一致）----
SPEEDS = [6.0, 8.0, 10.0]
TIS = [0.05, 0.10, 0.15]
SPACINGS_D = [2.0, 4.0, 6.0, 8.0]
MAX_ABS_OFFSET_DEG = 20.0          # 每间距盒按最大偏差取宽
N_TURBINES = 3
ROTOR_D = 126.0                    # NREL 5MW

# ---- 固定几何/时间参数 ----
HUB_HT = 175.0
GRID_HEIGHT = 340.0
NUMGRID_Z = 40
ANALYSIS_TIME = 600.0
USABLE_TIME = 600.0
REF_HT = 90.0
TIME_STEP = 0.05                   # TurbSim 内部步长；输出 10Hz 由 WrBLFF 决定
DT_OUT = 0.1                       # .bts 时间分辨率（匹配 DT_High=0.1）
DY_BOX_MAX = 9.43                  # 6 m/s 的 dY_Low_desired 上限


def required_gridwidth_m(spacing_D: float, offset_deg: float) -> float:
    """与 cases.required_gridwidth_m 同口径（此处独立实现以免耦合导入）。"""
    s_m = spacing_D * ROTOR_D
    xs = [i * s_m for i in range(N_TURBINES)]
    th = math.radians(-offset_deg)
    yr = [math.sin(th) * x for x in xs]
    ymean = sum(yr) / len(yr)
    yr = [y - ymean for y in yr]
    ymax = max(abs(y) for y in yr)
    span = max(yr) - min(yr)
    need_high = ymax + 1.0 * ROTOR_D          # 转子半跨 ~1D（含叶尖）
    need_low = span / 2.0 + 2.0 * ROTOR_D + 1.0 * ROTOR_D  # 走廊 2D + 蜿蜒 1D
    return 2.0 * max(need_high, need_low)


def box_params_for_spacing(spacing_D: float):
    """返回 (GridWidth, NumGrid_Y)，覆盖该间距全部 ±offset，且 dY_box<=9.43。"""
    w = required_gridwidth_m(spacing_D, MAX_ABS_OFFSET_DEG)
    grid_width = math.ceil(w / 20.0) * 20.0
    # NumGrid_Y 使 dY = W/(NY-1) <= 9.0（留余量到 9.43）
    ny = math.ceil(grid_width / 9.0) + 1
    dy = grid_width / (ny - 1)
    assert dy <= DY_BOX_MAX, f"dY={dy} > {DY_BOX_MAX} for s={spacing_D}"
    return grid_width, ny


