def ti_to_iecturbc(ti: float) -> float:
    return round(ti * 100.0, 1)


def fname(speed: float, ti: float, spacing_D: float) -> str:
    s = int(round(speed))
    t = int(round(ti * 100))
    return f"inflow_{s:02d}ms_TI{t:02d}_s{spacing_D:g}D.inp"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="./FarmInputs",
                    help="输出 .inp 目录")
    ap.add_argument("--seed", type=int, default=123456,
                    help="RandSeed1 起始值（逐盒 +1，保证各盒不同实现）")
    ap.add_argument("--generic", action="store_true",
                    help="只生成 9 个**通用盒**（inflow_06ms_TI05.bts，无 _sXD 后缀），"
                         "宽度按 offset=0 取（~760m）。适合当前 grid 只有 wd=0 的情况，"
                         "更省时省盘。工程会自动回退使用这些通用盒。")
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    # ---- 通用盒模式：9 个 (风速×TI)，宽度按 offset=0（列在 X 轴，ycoords=0）----
    if args.generic:
        w0 = required_gridwidth_m(2.0, 0.0)          # offset=0 时各间距相同
        grid_width = math.ceil(w0 / 20.0) * 20.0
        ny = math.ceil(grid_width / 9.0) + 1
        dy = grid_width / (ny - 1)
        print(f"通用盒（wd=0）：GridWidth={grid_width:.0f} m, NumGrid_Y={ny}, "
              f"dY={dy:.2f} m（<=9.43 ✓），共 {len(SPEEDS)*len(TIS)} 个\n")
        n = 0
        seed = args.seed
        for speed in SPEEDS:
            for ti in TIS:
                txt = TEMPLATE.format(
                    seed=seed, seed2=seed + 1000000, numgrid_z=NUMGRID_Z, numgrid_y=ny,
                    time_step=TIME_STEP, analysis_time=ANALYSIS_TIME,
                    usable_time=USABLE_TIME, hub_ht=HUB_HT,
                    grid_height=GRID_HEIGHT, grid_width=grid_width,
                    iecturbc=ti_to_iecturbc(ti), ref_ht=REF_HT, uref=speed,
                )
                s = int(round(speed)); t = int(round(ti * 100))
                (out / f"inflow_{s:02d}ms_TI{t:02d}.inp").write_text(txt)
                seed += 1
                n += 1
        print(f"已生成 {n} 个通用盒 .inp 到 {out.resolve()}")
        print("命名形如 inflow_06ms_TI05.inp；跑 TurbSim 得同名 .bts 放入 FarmInputs。")
        print("注意：这些盒**仅适用 wd=0**；要跑 ±偏差工况需改用 per-spacing 盒（去掉 --generic）。")
        return

    # 预览每间距的盒参数
    print("每间距盒参数（覆盖该间距全部 ±offset）：")
    per_spacing = {}
    for sp in SPACINGS_D:
        gw, ny = box_params_for_spacing(sp)
        per_spacing[sp] = (gw, ny)
        dy = gw / (ny - 1)
        print(f"  s={sp:g}D: GridWidth={gw:.0f} m, NumGrid_Y={ny}, dY={dy:.2f} m")
    print()

    n = 0
    seed = args.seed
    for sp in SPACINGS_D:
        gw, ny = per_spacing[sp]
        for speed in SPEEDS:
            for ti in TIS:
                txt = TEMPLATE.format(
                    seed=seed,
                    seed2=seed + 1000000,
                    numgrid_z=NUMGRID_Z,
                    numgrid_y=ny,
                    time_step=TIME_STEP,
                    analysis_time=ANALYSIS_TIME,
                    usable_time=USABLE_TIME,
                    hub_ht=HUB_HT,
                    grid_height=GRID_HEIGHT,
                    grid_width=gw,
                    iecturbc=ti_to_iecturbc(ti),
                    ref_ht=REF_HT,
                    uref=speed,
                )
                p = out / fname(speed, ti, sp)
                p.write_text(txt)
                seed += 1
                n += 1
    print(f"已生成 {n} 个 .inp 到 {out.resolve()}")
    print("命名形如 inflow_06ms_TI05_s8D.inp；跑 TurbSim 得到同名 .bts 后放入 FarmInputs。")
    print("工程会对每个工况优先使用 _s{spacing}D 专用盒（找不到才回退通用盒）。")


if __name__ == "__main__":
    main()
